"""Synthetic-truth coverage harness for the ensemble bands.

Role: a known theta_truth generates synthetic curves through the SAME frozen
forward form (station-aligned mirror) with a declared additive iid Gaussian
noise model; the deep-ensemble multi-start inversion runs on those synthetic
curves exactly as it would on measured ones; the harness reports the nominal
coverage of the ensemble bands = fraction of the truth components (12 for
form I, 14 for form II) lying inside [lower_i, upper_i]. Synthetic curves are
labeled CD (no CU offset term: they are generated by the same fixed-sigma_r
form, so no CTC-protocol mismatch exists by construction). Bands are
ensemble-based approximate credible bands -- under- or over-coverage measured
here is exactly the pre-registered posterior-calibration check of the claim
contract.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from . import ensemble
from .curves import synthetic_curveset
from .likelihood import load_likelihood_config, make_likelihood
from .theta_space import load_nominal_theta, space_for_form

# Form-II default coverage truth, fabric components: the AG-03 gate interior
# optimum (selfrev/evidence/AG-03_gate_anisotropy_reach.json,
# best_free_params.d_fab / best_free_params.q_fab). At d_fab = 0 the fabric
# scale is g = 1 for every q_fab (zeta = 0 identically), so q_fab would be
# structurally non-identifiable and its coverage row meaningless; the harness
# must test the form-II instrument in the active-fabric regime the round
# actually uses it in. The 12 matrix components stay at nominal, keeping the
# truth a one-change extension of the form-I coverage truth.
F2_COVERAGE_TRUTH_FABRIC = (0.6528079897943531, 0.9822690989944121)


def run_coverage(root: str | Path,
                 theta_truth: np.ndarray | None,
                 conditions: list[tuple[float, float]],
                 n_starts: int, n_iters: int, seed: int,
                 lr: float = 0.03,
                 noise_sigma: float | None = None,
                 start_scheme: str = "g0a_jitter",
                 form: int = 1,
                 p_conf_seqs=None) -> dict:
    """Run one synthetic-truth coverage test; returns bands + coverage.

    ``form`` selects the constitutive form (1 = frozen form I, the exact
    pre-existing code path; 2 = the 14-parameter fabric-scaled form II).
    Default truth (theta_truth is None): the nominal vector for form I; for
    form II the nominal 12-vector extended by F2_COVERAGE_TRUTH_FABRIC (see
    the constant's rationale above).
    """
    root = Path(root)
    space = space_for_form(form)
    nominal = load_nominal_theta(root)
    if theta_truth is None:
        truth = (np.asarray(nominal, dtype=float) if form == 1 else
                 np.concatenate([nominal, F2_COVERAGE_TRUTH_FABRIC]))
    else:
        truth = np.asarray(theta_truth, dtype=float)
    cfg = load_likelihood_config(root)
    sigma_noise = cfg.sigma_q if noise_sigma is None else float(noise_sigma)

    rng = np.random.default_rng(seed)
    synth = synthetic_curveset(truth, conditions, sigma_noise, rng, form=form,
                               p_conf_seqs=p_conf_seqs)
    like = make_likelihood(synth, cfg, form=form)

    starts = space.sample_starts(rng, n_starts, start_scheme,
                                 space.extend_nominal(nominal))
    records = ensemble.run_multistart(like.nll_z, starts, n_iters, lr=lr,
                                      form=form)
    bands = ensemble.aggregate_bands(records, form=form)

    lower = np.asarray(bands["lower"])
    upper = np.asarray(bands["upper"])
    inside = (lower <= truth) & (truth <= upper)
    return {
        "role": "synthetic-truth coverage harness (posterior-calibration check)",
        "noise_model": {
            "kind": "additive iid Gaussian on q at every station",
            "sigma_MPa": sigma_noise,
            "sigma_source": ("likelihood sigma_q (floored at the frozen-driver "
                             "transient noise floor)" if noise_sigma is None
                             else "explicit override"),
        },
        "conditions": [{"theta_deg": c[0], "sigma_r0_MPa": c[1]} for c in conditions],
        "synthetic_data_sha256": synth.data_sha256,
        "n_synthetic_curves": synth.n_curves,
        "n_starts": n_starts,
        "n_iters": n_iters,
        "lr": lr,
        "start_scheme": start_scheme,
        "theta_names": space.theta_names,
        "theta_truth": truth.tolist(),
        "bands": bands,
        "bands_well_formed": bool(np.all(lower <= upper)),
        "per_component_inside": inside.tolist(),
        "coverage_fraction": float(np.mean(inside)),
        "multistart_summary": ensemble.multistart_summary(records),
        "members": [r.as_dict() for r in records],
    }
